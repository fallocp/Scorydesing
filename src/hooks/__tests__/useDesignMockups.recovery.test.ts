import { beforeEach, describe, expect, it, vi } from 'vitest';

const fixture = vi.hoisted(() => ({
  actor: 'actor-a',
  activeBusiness: 'active-business',
  objects: new Map<string, Blob>(),
  rows: new Map<string, Record<string, unknown>>(),
  upload: vi.fn(), download: vi.fn(), from: vi.fn(), session: vi.fn(),
  failInsert: false,
}));

vi.mock('@/integrations/supabase/client', () => ({
  supabase: {
    auth: { getSession: fixture.session },
    from: fixture.from,
    storage: { from: () => ({
      upload: fixture.upload, download: fixture.download,
      getPublicUrl: (path: string) => ({ data: { publicUrl: `https://storage.test/design-images/${path}` } }),
    }) },
  },
}));
vi.mock('../useAuth', () => ({ useAuth: () => ({ user: { id: fixture.actor } }) }));
vi.mock('../useActiveBusiness', () => ({ useActiveBusiness: () => ({ activeBusinessId: fixture.activeBusiness }) }));
vi.mock('@tanstack/react-query', () => ({
  useQuery: vi.fn(), useQueryClient: () => ({ invalidateQueries: vi.fn() }),
  useMutation: ({ mutationFn }: { mutationFn: (params: unknown) => Promise<unknown> }) => ({ mutateAsync: mutationFn }),
}));

import { useSaveMockup, type SaveMockupParams } from '../useDesignMockups';

const operation = '10000000-0000-4000-8000-000000000001';
const input: SaveMockupParams = {
  mockupId: operation, businessId: 'original-business', actorId: 'actor-a',
  imageBase64: btoa('same generated bytes'), platform: 'banner', promptUsed: 'Original prompt',
  iterationFeedback: 'Keep globe', parentMockupId: 'parent-original',
};

beforeEach(() => {
  vi.clearAllMocks();
  fixture.objects.clear(); fixture.rows.clear(); fixture.actor = 'actor-a'; fixture.failInsert = false;
  fixture.session.mockImplementation(async () => ({ data: { session: { user: { id: fixture.actor } } }, error: null }));
  fixture.upload.mockImplementation(async (path: string, blob: Blob, options: { upsert: boolean }) => {
    expect(options.upsert).toBe(false);
    if (fixture.objects.has(path)) return { error: { statusCode: '409', message: 'The resource already exists' } };
    fixture.objects.set(path, blob); return { error: null };
  });
  fixture.download.mockImplementation(async (path: string) => ({ data: fixture.objects.get(path), error: null }));
  fixture.from.mockImplementation(() => {
    let inserted: Record<string, unknown> | null = null;
    const filters = new Map<string, unknown>();
    const query = {
      insert(row: Record<string, unknown>) { inserted = row; return query; },
      select() { return query; },
      eq(key: string, value: unknown) { filters.set(key, value); return query; },
      async single() {
        if (inserted) {
          if (fixture.failInsert) return { data: null, error: { code: '500', message: 'Connection lost' } };
          const id = String(inserted.id ?? 'legacy-generated-id');
          if (fixture.rows.has(id)) return { data: null, error: { code: '23505', message: 'Duplicate key' } };
          fixture.rows.set(id, { ...inserted, id }); return { data: { id }, error: null };
        }
        const found = [...fixture.rows.values()].find(row => [...filters].every(([key, value]) => row[key] === value));
        return { data: found ?? null, error: found ? null : { code: '404' } };
      },
    };
    return query;
  });
});

describe('idempotent Studio library persistence', () => {
  it('saves in the frozen business and reuses one immutable object and row on recovery', async () => {
    const save = useSaveMockup();
    const first = await save.mutateAsync(input);
    const recovered = await save.mutateAsync(input);
    expect(recovered).toEqual(first);
    expect(fixture.objects.size).toBe(1);
    expect(fixture.rows.size).toBe(1);
    expect(fixture.rows.get(operation)).toMatchObject({ business_id: input.businessId, created_by: input.actorId, parent_mockup_id: input.parentMockupId });
    expect(fixture.objects.has(`original-business/mockups/${operation}.png`)).toBe(true);
    expect(fixture.download).toHaveBeenCalledTimes(1);
  });

  it('recovers an uploaded image after the metadata write failed without overwriting bytes', async () => {
    const save = useSaveMockup(); fixture.failInsert = true;
    await expect(save.mutateAsync(input)).rejects.toThrow('Insert failed');
    expect(fixture.objects.size).toBe(1); expect(fixture.rows.size).toBe(0);
    fixture.failInsert = false;
    await save.mutateAsync(input);
    expect(fixture.objects.size).toBe(1); expect(fixture.rows.size).toBe(1);
  });

  it('rejects a conflicting file or a row owned by another actor', async () => {
    const save = useSaveMockup();
    await save.mutateAsync(input);
    await expect(save.mutateAsync({ ...input, imageBase64: btoa('different bytes') })).rejects.toThrow('no coincide');
    fixture.rows.get(operation)!.created_by = 'other-actor';
    await expect(save.mutateAsync(input)).rejects.toThrow('no coincide');
    expect(fixture.rows.size).toBe(1);
  });

  it('does not write metadata after the authenticated actor changes during upload', async () => {
    const upload = fixture.upload.getMockImplementation()!;
    fixture.upload.mockImplementation(async (...args: unknown[]) => {
      const result = await upload(...args); fixture.actor = 'actor-b'; return result;
    });
    await expect(useSaveMockup().mutateAsync(input)).rejects.toThrow('La sesión cambió');
    expect(fixture.rows.size).toBe(0);
  });

  it('preserves the existing save contract for callers with no operation identifier', async () => {
    await useSaveMockup().mutateAsync({ imageBase64: btoa('legacy image'), platform: 'instagram-post' });
    expect(fixture.rows.get('legacy-generated-id')).toMatchObject({ business_id: 'active-business', platform: 'instagram-post' });
    expect([...fixture.objects.keys()][0]).toMatch(/^active-business\/mockups\/.+\.png$/);
  });
});
