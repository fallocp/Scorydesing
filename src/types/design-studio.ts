/**
 * Piso y techo de una operación ilustrativa, en USD.
 *
 * Existían de facto en un solo valor: `amountUsd: 10000`, en todos los sets de todas
 * las industrias. Diez mil dólares es una compra creíble de mobiliario y es una cifra
 * absurda para una línea de producción, así que la pieza se leía como un ejemplo de
 * plantilla en la mitad de los casos.
 */
export const MIN_ILLUSTRATIVE_USD = 10_000;
export const MAX_ILLUSTRATIVE_USD = 150_000;

/**
 * El techo sube solo para obra e infraestructura.
 *
 * Es la excepción explícita: un proyecto de planta o de generación no se cotiza en el
 * mismo orden de magnitud que un contenedor de producto terminado, y forzarlo al techo
 * general produciría el mismo problema al revés.
 */
export const MAX_MEGA_PROJECT_USD = 250_000;

/** Sin acentos ni mayúsculas, para emparejar el nombre de la industria. */
function normalizeForMatch(value: string): string {
  return value
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

/**
 * Orden de magnitud de una compra, por industria.
 *
 * Bandas y no valores exactos: lo que la pieza necesita es una cifra PLAUSIBLE para
 * quien la lee, y dentro de la banda cualquiera lo es. Lo que no es plausible es la
 * misma cifra para todos.
 *
 * Las bandas van de más específica a más general y se evalúan en orden, porque
 * "maquinaria para planta solar" tiene que caer en obra y no en maquinaria.
 */
const ORDER_BANDS: { match: RegExp; min: number; max: number; label: string }[] = [
  {
    match: /obra|infraestructura|planta|construccion|energia|solar|eolic|mineria|refineria/,
    min: 90_000,
    max: MAX_MEGA_PROJECT_USD,
    label: 'proyecto de infraestructura',
  },
  {
    match: /maquinaria|industrial|equipo pesado|manufactura|cnc|torno|inyeccion|linea de produccion/,
    min: 55_000,
    max: MAX_ILLUSTRATIVE_USD,
    label: 'maquinaria industrial',
  },
  { match: /autoparte|automotriz|refaccion|ensamble/, min: 30_000, max: 90_000, label: 'autopartes' },
  {
    match: /electronic|componente|tecnolog|semiconductor|hardware|computo/,
    min: 25_000,
    max: 80_000,
    label: 'electrónica',
  },
  {
    match: /farmac|medic|salud|laboratorio|hospital/,
    min: 20_000,
    max: 70_000,
    label: 'insumos médicos',
  },
  { match: /alimento|agro|bebida|abarrote|empaque/, min: 18_000, max: 55_000, label: 'alimentos' },
  {
    match: /mueble|mobiliario|decorac|interiorismo|hogar/,
    min: 15_000,
    max: 45_000,
    label: 'mobiliario',
  },
  { match: /textil|ropa|calzado|moda|confeccion/, min: 12_000, max: 40_000, label: 'textil' },
];

/** Cuando la industria no se reconoce o no hay ninguna. */
const DEFAULT_ORDER_BAND = {
  min: 15_000,
  max: 60_000,
  label: 'importacion general',
} as const;

function orderBandFor(industryName?: string | null) {
  const name = normalizeForMatch(industryName?.trim() ?? '');
  if (!name) return DEFAULT_ORDER_BAND;
  return ORDER_BANDS.find((b) => b.match.test(name)) ?? DEFAULT_ORDER_BAND;
}

/**
 * Hash estable de una cadena. FNV-1a de 32 bits.
 *
 * Determinista a propósito, y es el punto: el mismo copy tiene que producir siempre la
 * misma cifra. Con un aleatorio, regenerar los prompts de un set ya renderizado
 * cambiaría los montos y dos slides del mismo carrusel cotizarían operaciones distintas.
 */
function stableSeed(text: string): number {
  let hash = 2166136261;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return Math.abs(hash | 0);
}

/**
 * El monto de la operación ilustrativa, deducido de la historia.
 *
 * Reemplaza al 10,000 fijo. La industria decide el orden de magnitud y el copy semilla
 * decide dónde cae dentro de esa banda, así que dos piezas de la misma industria no
 * cotizan lo mismo y la misma pieza cotiza siempre igual.
 *
 * Sigue siendo un valor ILUSTRATIVO y editable en el panel: esto solo cambia de qué
 * parte se arranca. Una cotización inventada no se presenta nunca como vigente ni como
 * oficial — eso ya lo dicen los prompts, y no cambia porque el monto ahora sea creíble.
 *
 * Se redondea a múltiplos de 500 porque una cotización real no termina en 37,412: un
 * monto con esa precisión invita a buscarle una fuente que no existe.
 */
export function illustrativeAmountUsd(params: {
  industryName?: string | null;
  /** El copy semilla. Es lo que hace que dos piezas de la misma industria difieran. */
  seed?: string | null;
}): number {
  const band = orderBandFor(params.industryName);
  const span = Math.max(0, band.max - band.min);
  const seed = stableSeed(params.seed?.trim() || band.label);

  const raw = band.min + (span === 0 ? 0 : seed % (span + 1));
  const rounded = Math.round(raw / 500) * 500;

  return Math.min(Math.max(rounded, MIN_ILLUSTRATIVE_USD), band.max);
}

/**
 * Standard illustrative case: USD 10,000 at 17.20, drifting +1% and +2%.
 *
 * One ceiling for the whole carousel (+2%) rather than a different percentage per
 * slide — the reader is following one mechanism, and unrelated percentages make it
 * look like unrelated examples. 2% keeps it plausible: a movement small enough to
 * be ignored and large enough to matter when it repeats. The +1% exists only so
 * the three-purchase comparison has a middle step.
 */
export const DEFAULT_CAROUSEL_FX: CarouselFxAssumptions = {
  baseRate: 17.2,
  /** Segunda cotización simultánea; nunca se interpreta como una tasa futura. */
  comparisonRate: 17.54,
  /**
   * Solo el respaldo. El monto real lo deduce `illustrativeAmountUsd` de la industria y
   * del copy: este valor es lo que se usa cuando el llamador no pasa nada, y quedarse en
   * él en producción es el fallo que la deducción vino a quitar.
   */
  amountUsd: 10000,
  /** Against the base: +1% and +2%. Not compounded — see `computeCarouselFx`. */
  driftPct: [1, 2],
  markupPct: DEFAULT_MARKUP_PCT,
};

/** One moment of the illustrative operation, with its text ready to render. */
export interface CarouselFxMoment {
  rate: number;
  amountUsd: number;
  amountMxn: number;
  /** Difference in MXN against the first moment. Zero on the first. */
  deltaMxn: number;
  /** Drift against the first moment, in percent. Zero on the first. */
  deltaPct: number;
  labels: {
    rate: string;
    usd: string;
    mxn: string;
    delta: string;
    pct: string;
  };
}

/** Thousands separators and two decimals, without depending on ICU. */
function formatAmount(value: number): string {
  const [int, dec] = Math.abs(value).toFixed(2).split('.');
  const grouped = int.replace(/\B(?=(\d{3})+(?!\d))/g, ',');
  return `${value < 0 ? '-' : ''}${grouped}.${dec}`;
}

/**
 * Derive the moments of the illustrative operation.
 *
 * The rate is rounded to two decimals BEFORE the multiplication, on purpose: the
 * piece shows both the rate and the total, so they have to agree when a reader
 * multiplies them by hand. Computing with full precision and rounding only for
 * display would print 17.47 next to 174,730 — off by 30 pesos and wrong to
 * anyone checking.
 *
 * Every drift is measured against the BASE moment, not against the previous one.
 * "+2%" has to mean one thing: with compounding, the third moment of a 1%/2% set
 * is +3.02% against the base while the label says +2%, and a piece that shows a
 * percentage next to the numbers it describes cannot afford that ambiguity.
 */
export function computeCarouselFx(a: CarouselFxAssumptions): CarouselFxMoment[] {
  // Every product is rounded to cents. Without this, 17.33 * 10000 lands on
  // 173299.99999999997 and the piece prints a total that is a cent short of the
  // multiplication it displays.
  const toCents = (n: number) => Math.round(n * 100) / 100;

  const baseRate = toCents(a.baseRate);
  const base = toCents(baseRate * a.amountUsd);

  const moment = (rate: number): CarouselFxMoment => {
    const rounded = toCents(rate);
    const amountMxn = toCents(rounded * a.amountUsd);
    const deltaMxn = toCents(amountMxn - base);
    const deltaPct = base === 0 ? 0 : Math.round((deltaMxn / base) * 1000) / 10;
    return {
      rate: rounded,
      amountUsd: a.amountUsd,
      amountMxn,
      deltaMxn,
      deltaPct,
      labels: {
        rate: formatAmount(rounded).replace(/,/g, ''),
        usd: `USD ${formatAmount(a.amountUsd)}`,
        mxn: `MXN ${formatAmount(amountMxn)}`,
        delta: deltaMxn === 0 ? '' : `+MXN ${formatAmount(deltaMxn)}`,
        pct: deltaPct === 0 ? '' : `+${deltaPct.toFixed(1)}%`,
      },
    };
  };

  /*
   * Tasa expuesta explícita: el forward. Dos momentos exactos —la pactada y la posible—
   * en vez de una deriva sintética. El usuario da las dos tasas; el código no inventa
   * ninguna. Si la expuesta iguala a la pactada, sigue habiendo dos momentos (delta cero),
   * porque la historia es la comparación, no el movimiento.
   */
  if (a.exposedRate !== undefined) {
    return [moment(baseRate), moment(a.exposedRate)];
  }

  return [0, ...a.driftPct].map((drift) => moment(baseRate * (1 + drift / 100)));
}

/** One line of a document in the scene: a field name and its exact value. */
export interface CarouselFigureField {
  label: string;
  value: string;
  /** Meaning of the value, which resolves its colour. Omitted = neutral navy. */
  colorRole?: CarouselColorRole;
}

/**
 * A document in the scene, with every visible value already decided.
 *
 * This replaced a flat list of labels, and the reason is worth keeping: given
 * `["TOTAL USD 10,000.00", "TIPO DE CAMBIO 18.38", "TIPO DE CAMBIO 18.56", ...]`
 * the image model has no way to know which value belongs to which card, so it put
 * the same numbers on all three and pulled a stray "+4.0%" out of the pile. Data
 * for several documents has to be shaped like several documents.
 */
export interface CarouselFigureDocument {
  /** 'HOY', 'PAGO', 'COMPRA 1'. Doubles as the stamp on the document. */
  label: string;
  /** 'COTIZACIÓN', 'FACTURA'. The document has to look like something. */
  kind: string;
  date?: string;
  fields: CarouselFigureField[];
  /** Always present: a quote explaining a cost without a TOTAL reads unfinished. */
  total: CarouselFigureField;
}

/** Which numeric story a slide is telling. */
export type CarouselFigureScenario = 'two_moment' | 'repeated_purchases';

const MONTHS_ES = [
  'ENE', 'FEB', 'MAR', 'ABR', 'MAY', 'JUN',
  'JUL', 'AGO', 'SEP', 'OCT', 'NOV', 'DIC',
];

/** '20 JUN 2026' — the format these documents print. */
export function formatFigureDate(date: Date): string {
  return `${String(date.getDate()).padStart(2, '0')} ${MONTHS_ES[date.getMonth()]} ${date.getFullYear()}`;
}

function shiftDays(base: Date, days: number): Date {
  const next = new Date(base);
  next.setDate(next.getDate() + days);
  return next;
}

/**
 * Turn the computed moments into the documents a slide renders.
 *
 * The field set is identical across documents of the same scenario, in the same
 * order, because that is what makes a comparison readable: the eye finds the one
 * value that changed instead of re-reading two different layouts. The only
 * asymmetry allowed is the variation line, which the base case does not have
 * because there is nothing yet to vary against.
 *
 * Dates are derived from `today` rather than hardcoded so the pieces do not carry
 * a stale year.
 *
 * The two-moment case takes the first and LAST moment, skipping the middle steps.
 * Its claim is what the movement costs by payment day, so it needs the full gap
 * (17.20 → 17.54); the intermediate +1% exists only for the three-purchase
 * comparison, and using it here would show a smaller number than the story states.
 */
export function buildFigureDocuments(
  scenario: CarouselFigureScenario,
  moments: CarouselFxMoment[],
  today: Date = new Date(),
): CarouselFigureDocument[] {
  const labels = scenario === 'two_moment'
    ? ['HOY', 'PAGO']
    : ['COMPRA 1', 'COMPRA 2', 'COMPRA 3'];
  const dayOffsets = scenario === 'two_moment' ? [0, 60] : [0, 35, 70];

  const selected = scenario === 'two_moment' && moments.length > 1
    ? [moments[0], moments[moments.length - 1]]
    : moments.slice(0, labels.length);

  return selected.map((m, i) => {
    const fields: CarouselFigureField[] = [
      // Navy: the obligation is neither the benefit nor the risk, and it is the
      // value that must read as identical across every document.
      { label: 'TOTAL USD', value: m.labels.usd.replace('USD ', '') },
      {
        label: 'TIPO DE CAMBIO',
        value: m.labels.rate,
        colorRole: i === 0 ? 'control' : 'risk',
      },
      {
        label: 'COSTO MXN',
        value: m.labels.mxn.replace('MXN ', ''),
        colorRole: i === 0 ? 'control' : 'risk',
      },
    ];

    if (m.labels.pct) {
      fields.push({ label: 'VARIACIÓN', value: m.labels.pct, colorRole: 'risk' });
    }

    return {
      label: labels[i],
      kind: 'COTIZACIÓN',
      date: formatFigureDate(shiftDays(today, dayOffsets[i])),
      fields,
      total: {
        label: 'TOTAL',
        value: m.labels.mxn.replace('MXN ', ''),
        colorRole: i === 0 ? undefined : 'risk',
      },
    };
  });
}

/**
 * What the repetition slide is actually about: the differences adding up.
 *
 * Each purchase costs more in pesos than the first one did, and the slide's claim is
 * that those gaps compound. That total is the number the piece needs — showing three
 * growing totals without it leaves the reader to do the addition.
 */
export function accumulatedFxImpact(moments: CarouselFxMoment[]): {
  amount: number;
  label: string;
} {
  const amount = Math.round(moments.reduce((sum, m) => sum + m.deltaMxn, 0) * 100) / 100;
  return {
    amount,
    label: amount === 0 ? '' : `+MXN ${formatAmount(amount)}`,
  };
}

const toCents = (value: number): number => Math.round(value * 100) / 100;
const toTenth = (value: number): number => Math.round(value * 10) / 10;

/*
 * Etiquetas del forward: el lenguaje del negocio, no el técnico, y según la dirección.
 *
 * Importas: debes USD, lo VARIABLE es tu COSTO y lo fijo tu precio de venta; el riesgo es
 * que el dólar SUBA. Exportas: te pagan USD, lo VARIABLE es tu INGRESO y lo fijo tu costo;
 * el riesgo es que el dólar BAJE. La misma mecánica, vocabulario invertido.
 */
const FORWARD_FACT_LABELS_IMPORT: Partial<Record<CarouselEconomicFactKey, string>> = {
  base_rate: 'TC PRESUPUESTADO',
  exposed_rate: 'TC AL PAGO',
  base_cost_mxn: 'COSTO PRESUPUESTADO',
  exposed_cost_mxn: 'COSTO AL PAGO',
  cost_delta_mxn: 'AUMENTO DE COSTO',
  cost_delta_pct: 'VARIACIÓN',
  base_gross_profit_mxn: 'UTILIDAD PRESUPUESTADA',
  exposed_gross_profit_mxn: 'UTILIDAD AL PAGO',
  base_gross_margin_pct: 'MARGEN PRESUPUESTADO',
  exposed_gross_margin_pct: 'MARGEN AL PAGO',
  sale_price_mxn: 'PRECIO DE VENTA FIJO',
};

