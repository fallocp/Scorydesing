  base_rate: 'FORWARD PACTADO',
  base_cost_mxn: 'INGRESO FINAL',
  base_gross_profit_mxn: 'UTILIDAD DEFINIDA',
  base_gross_margin_pct: 'MARGEN PROTEGIDO',
