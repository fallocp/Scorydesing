/**
 * Assumptions behind the numbers a carousel is allowed to show.
 *
 * These exist because the figures have to be arithmetically coherent: a piece
 * showing "USD 8,750" next to "MXN 157,980" is implicitly quoting a rate of
 * 18.06 that nobody chose, and anyone who divides catches it. The rate is an
 * input rather than something the model picks, and every other number is derived
 * from it in code — language models are unreliable at arithmetic, and here the
 * arithmetic IS the message.
 */
export interface CarouselFxAssumptions {
  /** Illustrative rate, set by the user. Never presented as a market quote. */
  baseRate: number;
  /** Segunda tasa editable para comparar cotizaciones simultáneas. */
  comparisonRate?: number;
  /** USD amount of the illustrative operation. */
  amountUsd: number;
  /**
   * Drift of each later moment against the BASE rate, in percent — not against
   * the previous one. Small on purpose: the point is that a small movement
   * repeated adds up, not that the purchases got bigger.
   */
  driftPct: number[];
  /** Markup objetivo sobre costo importado. Es la semántica real del cálculo. */
  markupPct?: number;
  /**
   * @deprecated Alias persistido anterior. También representaba markup sobre costo,
   * no margen bruto; se lee solo para compatibilidad.
   */
  marginPct?: number;
  /**
   * Tasa expuesta explícita del escenario forward. Cuando está presente, el momento
   * expuesto usa esta tasa tal cual en vez de derivarla de `driftPct`: es la tasa que el
   * usuario cree posible a `daysAhead` si no cubre.
   */
  exposedRate?: number;
  /**
   * Precio de venta comprometido, en MXN, dado por el usuario. Presente => el forward
   * cuenta la historia de margen; ausente => solo el delta de costo.
   *
   * Su semántica depende de `direction`: en importación es el PRECIO DE VENTA (ingreso
   * fijo); en exportación es el COSTO fijo. El motor calcula el margen en consecuencia.
   */
  salePriceMxn?: number;
  /** Horizonte del escenario forward, en días. Solo etiqueta, nunca fecha de calendario. */
  daysAhead?: number;
  /**
   * Dirección de la operación forward. Importación (debes USD, riesgo = dólar sube) o
   * exportación (te pagan USD, riesgo = dólar baja). Cambia qué es fijo y qué variable, y
   * el vocabulario (costo ↔ ingreso). Por defecto 'import'.
   */
  direction?: CarouselFxDirection;
}

/** Dirección de la operación forward. */
export type CarouselFxDirection = 'import' | 'export';

/**
 * Margen objetivo cuando el llamador no declara ninguno.
 *
 * 35% sobre costo es un margen de reventa creíble para un importador de producto
 * terminado, y está elegido para que la historia funcione: con un margen muy alto, un
 * movimiento del 2% en el costo no se nota en el cuadro y la pieza no demuestra nada; con
 * uno muy bajo el margen queda casi en cero y se lee como una afirmación de pérdida, que
 * el kit editorial prohíbe.
 */
export const DEFAULT_MARKUP_PCT = 35;
/** @deprecated Nombre anterior; se conserva para callers persistidos. */
export const DEFAULT_MARGIN_PCT = DEFAULT_MARKUP_PCT;

